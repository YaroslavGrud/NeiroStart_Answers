def count_down():
    number = 10  # Устанавливаем начальное значение счётчика
    while number >= 1:  # Запускаем цикл, который будет работать, пока number больше или равно 1
        print(number)  # Выводим текущее значение счётчика
        number -= 1  # Уменьшаем значение счётчика на 1

count_down()  # Вызываем функцию