# Инициализируем счетчик имен
count = 0

# Открываем файл и читаем его содержимое
with open('names.txt', 'r', encoding='utf-8') as file:
    # Перебираем каждую строку в файле
    for line in file:
        # Удаляем пробелы и переносы строк
        name = line.strip()

        # Проверяем, начинается ли имя на букву "А"
        if name.startswith('А'):
            count += 1

# Выводим результат
print(f"Количество имен, начинающихся на букву 'А': {count}")
