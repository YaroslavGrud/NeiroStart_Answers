# Инициализируем счетчик имен длиной 5 символов
count = 0

# Открываем файл и читаем его содержимое
with open('names.txt', 'r', encoding='utf-8') as file:
    # Перебираем каждую строку в файле
    for line in file:
        # Удаляем пробелы и переносы строк
        name = line.strip()

        # Проверяем длину имени
        if len(name) == 5:
            count += 1

# Выводим результат
print(f"Количество имен длиной ровно 5 символов: {count}")
