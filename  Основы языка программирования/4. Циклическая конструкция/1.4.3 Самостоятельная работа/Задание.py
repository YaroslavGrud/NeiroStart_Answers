# Инициализируем счётчик с начального значения 1
i = 1

# Цикл while: продолжаем, пока i не превысит 10
while i <= 10:
    # Проверяем, является ли число чётным (остаток от деления на 2 равен 0)
    if i % 2 == 0:
        # Выводим чётное число на отдельной строке
        print(i)
    # Увеличиваем счётчик на 1 для перехода к следующему числу
    i += 1