books = {
    "Гарри Поттер": 9,
    "Война и мир": 10,
    "Мастер и Маргарита": 8,
    "Унесённые ветром": 6,
    "1984": 9,
    "Преступление и наказание": 7,
    "Три товарища": 10,
}

# Извлекаем все значения рейтингов из словаря
ratings = books.values()

# Считаем сумму всех рейтингов
total_sum = sum(ratings)

# Определяем количество книг
count = len(books)

# Вычисляем средний рейтинг
average_rating = total_sum / count

# Выводим результат с одним знаком после запятой
print(f"{average_rating:.1f}")
